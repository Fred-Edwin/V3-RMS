import { env } from '../../../../config/env';
import { CONTENT, PALETTE, PORTRAIT, addPortraitPage, drawQr, footers, hline, letterhead, openPortrait, put, shillings, signature } from '../../_shared/documents/portrait-doc';
import { monthLabel } from '../documents/document-model';
import { P9_COLUMNS } from './p9-layout';
import type { P9Row, P9Values } from './p9-model';

export interface P9Doc {
  number: string;
  layoutVersion: number;
  year: number;
  site: string;
  employee: { name: string; number: string; kraPin: string; jobTitle: string };
  rows: P9Row[];
  totals: P9Values;
  signer: { name: string; roleLine: string; signedAt: string } | null;
  generatedLong: string;
  created: Date;
  hashPrefix: string;
}

const X = PORTRAIT.marginX;
const FIRST = 74;
const COL_W = (CONTENT - FIRST) / P9_COLUMNS.length;

/** The Tax Deduction Card (S12). Structure only: the columns come from the layout definition, every figure from the frozen payslips. */
export async function renderP9Pdf(model: P9Doc): Promise<Buffer> {
  const { doc, script, done } = openPortrait({ title: `Tax deduction card P9 · ${model.year}`, subject: model.number, created: model.created });
  addPortraitPage(doc, null);
  let y = letterhead(doc, { site: model.site, label: 'TAX DEDUCTION CARD · P9', number: model.number, line: `Tax year ${model.year}`, extra: `Generated ${model.generatedLong}${model.layoutVersion > 1 ? ` · layout version ${model.layoutVersion}` : ''}` });
  const e = model.employee;
  const pairs: [string, string][] = [['EMPLOYEE', e.name], ['EMPLOYEE NO.', e.number], ['KRA PIN', e.kraPin], ['JOB TITLE', e.jobTitle]];
  pairs.forEach(([label, value], i) => {
    const x = X + (i % 2) * 270;
    const yy = y + Math.floor(i / 2) * 30;
    put(doc, label, x, yy, { size: 7, color: PALETTE.muted, width: 250, spacing: 0.5 });
    put(doc, value, x, yy + 9, { size: 10.5, width: 250 });
  });
  y += 76;
  hline(doc, y, X, X + CONTENT, PALETTE.navy, 2);
  put(doc, 'MONTH', X + 4, y + 6, { font: 'Times-Bold', size: 7.5, color: PALETTE.navy, width: FIRST, spacing: 0.5 });
  P9_COLUMNS.forEach((c, i) => put(doc, c.label.toUpperCase(), X + FIRST + i * COL_W, y + 4, { font: 'Times-Bold', size: 6.5, color: PALETTE.navy, width: COL_W - 6, align: 'right' }));
  y += 22;
  hline(doc, y, X, X + CONTENT, PALETTE.navy, 0.8);
  for (const row of model.rows) {
    put(doc, monthLabel(row.monthKey).split(' ')[0] ?? row.monthKey, X + 4, y + 6, { size: 9.5, width: FIRST });
    if (row.values) {
      P9_COLUMNS.forEach((c, i) => put(doc, shillings(row.values![c.key], 2), X + FIRST + i * COL_W, y + 6, { size: 9, width: COL_W - 6, align: 'right' }));
    } else {
      put(doc, row.state === 'NOT_EMPLOYED' ? 'Not employed' : 'No payslip', X + FIRST, y + 6, { font: 'Times-Italic', size: 9, color: PALETTE.muted, width: CONTENT - FIRST });
    }
    y += 21;
    hline(doc, y, X, X + CONTENT, PALETTE.row, 0.5);
  }
  doc.save().rect(X, y + 2, CONTENT, 22).fill(PALETTE.band).restore();
  put(doc, 'TOTAL', X + 4, y + 8, { font: 'Times-Bold', size: 9.5, width: FIRST });
  P9_COLUMNS.forEach((c, i) => put(doc, shillings(model.totals[c.key], 2), X + FIRST + i * COL_W, y + 8, { font: 'Times-Bold', size: 9, width: COL_W - 6, align: 'right' }));
  y += 40;
  put(doc, `Employer: Wendo Coffee Bistro · Total gross pay KES ${shillings(model.totals.gross, 2)} · Total PAYE KES ${shillings(model.totals.paye, 2)}`, X, y, { size: 9.5, width: CONTENT });
  y += 28;
  if (model.signer) signature(doc, script, { x: X, y, width: 220, name: model.signer.name, roleLine: model.signer.roleLine, signedLine: `Signed with PIN · ${model.signer.signedAt}` });
  drawQr(doc, `${env.FRONTEND_ORIGIN.replace(/\/$/, '')}/verify/p9/${model.number}?h=${model.hashPrefix}`, X + CONTENT - 62, y, 62);
  put(doc, `Scan to open ${model.number}`, X + CONTENT - 120, y + 66, { size: 7.5, color: PALETTE.muted, width: 120, align: 'right' });
  footers(doc, `Generated by Wendo RMS · ${model.number}`, 'Keep for your KRA return');
  doc.end();
  return done;
}
