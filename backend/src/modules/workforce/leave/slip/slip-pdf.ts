import { CONTENT, PALETTE, PORTRAIT, addPortraitPage, drawQr, footers, hline, letterhead, openPortrait, put, signature, stamp } from '../../_shared/documents/portrait-doc';
import { slipCode, type SlipSnapshot } from './slip-snapshot';
import { longDate, slipLines, stampLine } from './slip-text';

export interface SlipCancel {
  at: string; // ISO instant
  byRole: string; // 'Branch Manager'
}

export interface SlipRender {
  snapshot: SlipSnapshot;
  /** The QR text, `{origin}/verify/lve/{number}?h={hash prefix}`. */
  qrUrl: string;
  cancelled: SlipCancel | null;
}

const X = PORTRAIT.marginX;

/**
 * The A4 portrait leave slip (spec section 7). Drawn from the frozen snapshot alone and with the document dates fixed to the approval
 * moment, so a re-render has the same bytes. A cancelled slip is the same page with a VOID watermark, a CANCELLED stamp and a line.
 */
export async function renderSlipPdf(model: SlipRender): Promise<Buffer> {
  const s = model.snapshot;
  const code = slipCode(s.number);
  const lines = slipLines(s);
  const { doc, script, done } = openPortrait({ title: `Leave slip ${code}`, subject: code, created: new Date(s.approvedAt) });
  addPortraitPage(doc, model.cancelled ? 'VOID' : null);
  let y = letterhead(doc, { site: `${s.person.site} branch`, label: 'LEAVE SLIP', number: code, line: longDate(s.approvedAt.slice(0, 10)) });
  y += 14;
  put(doc, s.person.name, X, y, { font: 'Times-Bold', size: 13, width: CONTENT });
  put(doc, `${s.person.roleLabel} · ${s.person.site}`, X, y + 17, { size: 10, color: PALETTE.muted, width: CONTENT });
  y += 52;
  put(doc, lines.heading, X, y, { font: 'Times-Bold', size: 14, color: PALETTE.navy, width: CONTENT });
  y += 30;
  if (model.cancelled) {
    stamp(doc, 'CANCELLED', X, y);
    put(doc, `Cancelled on ${longDate(new Date(new Date(model.cancelled.at).getTime() + 3 * 3_600_000).toISOString().slice(0, 10))} by ${model.cancelled.byRole}. The days were returned to the balance.`, X + 110, y + 5, { size: 9.5, color: PALETTE.muted, width: CONTENT - 110 });
    y += 34;
  }
  for (const paragraph of lines.paragraphs) {
    doc.font('Times-Roman').fontSize(11).fillColor(PALETTE.ink);
    const height = doc.heightOfString(paragraph, { width: CONTENT, lineGap: 3 });
    doc.text(paragraph, X, y, { width: CONTENT, lineGap: 3 });
    y += height + 12;
  }
  y += 14;
  signature(doc, script, { x: X, y, width: 230, name: s.approver.name, roleLine: lines.roleLine, signedLine: lines.signedLine });
  drawQr(doc, model.qrUrl, X + CONTENT - 76, y - 4, 76);
  put(doc, `Scan to open ${code}`, X + CONTENT - 130, y + 76, { size: 8, color: PALETTE.muted, width: 130, align: 'right' });
  hline(doc, y + 100, X, X + CONTENT, PALETTE.rule, 0.6);
  put(doc, `Issued ${stampLine(s.approvedAt)}`, X, y + 106, { size: 8, color: PALETTE.muted, width: CONTENT });
  footers(doc, `Generated by Wendo RMS · ${code}`, lines.footerRight);
  doc.end();
  return done;
}
