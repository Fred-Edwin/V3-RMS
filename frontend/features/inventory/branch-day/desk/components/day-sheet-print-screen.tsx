const COL = `font-wds-mono text-[9px] leading-3 tracking-[0.06em] ${SLATE}`;

const stamp = (iso: string): string => {
  const p = new Intl.DateTimeFormat('en-GB', { timeZone: 'Africa/Nairobi', day: 'numeric', month: 'short', year: 'numeric' }).format(new Date(iso));
  return `${p}, ${clock12(iso)}`;
};

/** The wording of a department's footnote about its corrections: `*`, `**`, one for each corrected line (gap G18). */
const marks = (n: number): string => '*'.repeat(n);

