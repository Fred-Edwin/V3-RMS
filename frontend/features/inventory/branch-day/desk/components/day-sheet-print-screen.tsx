// The print palette of Paper B13b to B13d (no wds tokens; the sheet is a document, not a screen).
const NAVY = 'text-[#0B2A4A]';
const SLATE = 'text-[#6B7785]';
const BODY = 'text-[#3A4756]';
const RULE = 'bg-[#D5DCE4]';
