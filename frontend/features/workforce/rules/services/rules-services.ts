import { apiClient } from '@/lib/apiClient';
import { useAuthStore } from '@/store/authStore';

import type { AccessTableRow, ChangeBody, HistoryAnswer, Preview, RuleGroupCode, RulesPageAnswer, SavedVersion, VersionView } from '../types/rules-types';

/** One function per Rules endpoint (R2 to R8, docs/API_CONTRACT.md §39). R1 (`/effective`) is for the system, not these screens. */
const BASE = '/workforce/rules';
const token = (): string | undefined => useAuthStore.getState().accessToken ?? undefined;

function query(params: Record<string, string | number | null | undefined>): string {
  const pairs = Object.entries(params).filter((entry): entry is [string, string | number] => entry[1] !== undefined && entry[1] !== null && entry[1] !== '');
  return pairs.length === 0 ? '' : `?${pairs.map(([k, v]) => `${encodeURIComponent(k)}=${encodeURIComponent(String(v))}`).join('&')}`;
}

export const rulesReads = {
  /** R3: one tab for this viewer. `organizationId` absent = the company rule (a branch holder always gets their own site). */
  page: (group: RuleGroupCode, organizationId: string | null): Promise<RulesPageAnswer> => apiClient.get(`${BASE}/${group}${query({ siteId: organizationId })}`, token()),
  /** R4: history, newest first. */
  history: (group: RuleGroupCode, organizationId: string | null, page: number, pageSize: number): Promise<HistoryAnswer> =>
    apiClient.get(`${BASE}/${group}/versions${query({ siteId: organizationId, page, pageSize })}`, token()),
  /** R2: the "Who edits what" table, generated by the server. */
  accessTable: (): Promise<{ rows: AccessTableRow[] }> => apiClient.get(`${BASE}/access-table`, token()),
};

export interface SaveBody extends ChangeBody {
  reason: string;
  pin: string;
  /** Makes a retry safe: the same key answers with the first result. */
  idempotencyKey: string;
}

const wire = (body: ChangeBody): Record<string, unknown> => ({
  siteId: body.organizationId,
  effectiveFrom: body.effectiveFrom,
  values: body.values,
  ...(body.useCompanyRuleFor ? { useCompanyRuleFor: body.useCompanyRuleFor } : {}),
  ...(body.expectedVersion !== undefined ? { expectedVersion: body.expectedVersion } : {}),
});

export const rulesWrites = {
  /** R5: no side effects. */
  preview: (group: RuleGroupCode, body: ChangeBody): Promise<Preview> => apiClient.post(`${BASE}/${group}/versions/preview`, wire(body), token()),
  /** R6 */
  create: (group: RuleGroupCode, body: SaveBody): Promise<SavedVersion> =>
    apiClient.post(`${BASE}/${group}/versions`, { ...wire(body), reason: body.reason, pin: body.pin, idempotencyKey: body.idempotencyKey }, token()),
  /** R7 */
  confirm: (versionId: string, scope: string, pin: string): Promise<{ version: VersionView }> => apiClient.post(`${BASE}/versions/${versionId}/confirm`, { scope, pin }, token()),
  /** R8 */
  withdraw: (versionId: string, reason: string, pin: string): Promise<{ version: VersionView }> => apiClient.post(`${BASE}/versions/${versionId}/withdraw`, { reason, pin }, token()),
};
