'use client';

import * as React from 'react';
import Link from 'next/link';

import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from '@/components/ui2/table';
import { cn } from '@/lib/cn';

import { Callout, ErrorBlock, FOCUS_RING, ListSkeleton, PageHeader, WorkforceFrame, onHover, useWorkforcePermissions } from '../../_shared';
import { useAccessTable } from '../hooks/use-rules-data';
import { rulesHref } from '../lib/tab-defs';

const cap = (s: string): string => s.charAt(0).toUpperCase() + s.slice(1);

/** "Who edits what" (Paper Chapter 13 step 13): the same table the Rules screen uses, generated by the server from the access table. */
export function AccessScreen() {
  const permissions = useWorkforcePermissions();
  const enabled = permissions.ready && permissions.can('rules.read');
  const remote = useAccessTable(enabled);
  const denied = (permissions.ready && !enabled) || (remote.status === 'error' && remote.error.status === 403);

  return (
    <WorkforceFrame breadcrumb={{ section: 'Settings', screen: 'Rules', sectionHref: rulesHref('lateness') }} phoneTitle="Rules" label="Who edits what" className="px-4 py-6 lg:px-8 lg:py-7">
      <div className="mx-auto flex w-full max-w-[1140px] flex-col gap-5">
        {denied ? (
          <ErrorBlock title="You do not have access to Rules" line="Ask the Director." />
        ) : (
          <>
            <Link href={rulesHref('lateness')} className={cn('w-fit font-wds-sans text-[13px] leading-4 text-wds-info-fg', FOCUS_RING, onHover('underline'))}>
              ← Back to Rules
            </Link>
            <PageHeader
              size="lg"
              title="Rules · who edits what"
              subtitle="The same table the Rules screen uses. Everyone who can open Rules sees every tab and a Change link on every row. Where a person cannot change a row, the link shows a padlock and says who can; rows set by the system say Fixed."
            />
            {remote.status === 'loading' ? (
              <ListSkeleton rows={6} label="Loading the table" />
            ) : remote.status === 'error' ? (
              <ErrorBlock title="We could not load the table" line="Nothing was changed." reference={remote.error.code} onRetry={remote.reload} />
            ) : (
              <>
                <Table look="workforce" aria-label="Who edits what">
                  <TableHeader>
                    <TableRow>
                      <TableHead>TAB</TableHead>
                      <TableHead>CHANGED BY</TableHead>
                      <TableHead>CONFIRMED BY</TableHead>
                      <TableHead>TOLD WHEN IT CHANGES</TableHead>
                    </TableRow>
                  </TableHeader>
                  <TableBody>
                    {remote.data.rows.map((row) => (
                      <TableRow key={row.group}>
                        <TableCell className="font-semibold">
                          <Link href={rulesHref(row.slug)} className={cn(FOCUS_RING, onHover('underline'))}>{row.label}</Link>
                        </TableCell>
                        <TableCell className="whitespace-normal">{cap(row.text.changedBy)}</TableCell>
                        <TableCell className="whitespace-normal">{cap(row.text.confirmedBy)}</TableCell>
                        <TableCell className="whitespace-normal">{cap(row.text.told)}</TableCell>
                      </TableRow>
                    ))}
                  </TableBody>
                </Table>
                <p className="m-0 font-wds-sans text-[12px] leading-4 text-wds-text-secondary">Showing {remote.data.rows.length} of {remote.data.rows.length} tabs · every change is logged and its wording is in the shared Notifications table</p>
                <Callout tone="neutral" variant="dashed">A Branch Manager can set an own rule for Lateness, Overtime and minimum cover at their own site only.</Callout>
              </>
            )}
          </>
        )}
      </div>
    </WorkforceFrame>
  );
}
