import { createElement as h } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { describe, expect, it } from 'vitest';

import { DOC_COLOURS, DOC_PAGE } from '../../lib/style/document-palette';
import { AttentionRow, DrawerSection, MiniBar } from '../phone/home-parts';
import { DocHeading, DocParagraph, DocumentCanvas, WorkforceDocument } from '../documents/workforce-document';

const html = (el: Parameters<typeof renderToStaticMarkup>[0]): string => renderToStaticMarkup(el);
const noop = (): void => undefined;

describe('AttentionRow', () => {
  it('draws a 3 px bar in the tone and the detail in the tone colour', () => {
    const out = html(h(AttentionRow, { tone: 'error', name: 'Esther Mwende', detail: 'Not in · due 06:00' }));
    expect(out).toContain('w-[3px]');
    expect(out).toContain('bg-wds-error-fg');
    expect(out).toContain('text-wds-error-fg');
  });
  it('has a button only when an action is passed', () => {
    expect(html(h(AttentionRow, { tone: 'warning', name: 'a', detail: 'b' }))).not.toContain('<button');
    const out = html(h(AttentionRow, { tone: 'error', name: 'a', detail: 'b', action: { label: 'Clock in for her', onClick: noop } }));
    expect(out).toContain('<button');
    expect(out).toContain('Clock in for her');
  });
  it('can show a mini bar instead of a button', () => {
    const out = html(h(AttentionRow, { tone: 'warning', name: 'a', detail: 'b', bar: { fraction: 0.5, label: '15 of 30 minutes' } }));
    expect(out).toContain('width:50%');
    expect(out).not.toContain('<button');
  });
});

describe('MiniBar', () => {
  it('is 84 by 6 and clamps its fill', () => {
    const out = html(h(MiniBar, { fraction: 4 }));
    expect(out).toContain('w-[84px]');
    expect(out).toContain('h-1.5');
    expect(out).toContain('width:100%');
    expect(html(h(MiniBar, { fraction: -1 }))).toContain('width:0%');
  });
});

describe('DrawerSection', () => {
  it('puts a mono caption over its content and names the section', () => {
    const out = html(h(DrawerSection, { caption: 'TODAY', children: 'body' }));
    expect(out).toContain('aria-label="TODAY"');
    expect(out).toContain('font-wds-mono');
  });
});

describe('document palette', () => {
  it('is A4: 794 by 1123, landscape 1123 by 794', () => {
    expect(DOC_PAGE.portrait).toEqual({ width: 794, height: 1123 });
    expect(DOC_PAGE.landscape).toEqual({ width: 1123, height: 794 });
  });
  it('holds Paper’s navy', () => {
    expect(DOC_COLOURS.navy).toBe('#14284B');
  });
});

describe('WorkforceDocument', () => {
  const base = { type: 'LEAVE SLIP', number: 'LVE-0031', date: '9 October 2026', branchLine: 'Nyeri Town branch · Nyeri, Kenya', footerLeft: 'Generated by Wendo RMS · LVE-0031 · Page 1 of 1' };
  it('draws the navy bar, the header and the footer at A4 portrait', () => {
    const out = html(h(WorkforceDocument, { ...base, children: 'body' }));
    expect(out).toContain('width:794px');
    expect(out).toContain('min-height:1123px');
    expect(out).toContain('background-color:#14284B');
    expect(out).toContain('Wendo Coffee Bistro');
    expect(out).toContain('LEAVE SLIP');
    expect(out).toContain('LVE-0031');
    expect(out).toContain('Generated by Wendo RMS');
    expect(out).toContain('print-exact');
    expect(out).toContain('Times New Roman');
  });
  it('is 1123 wide in landscape', () => {
    expect(html(h(WorkforceDocument, { ...base, orientation: 'landscape', children: 'x' }))).toContain('width:1123px');
  });
  it('shows the signature and the QR only when given', () => {
    expect(html(h(WorkforceDocument, { ...base, children: 'x' }))).not.toContain('Signed with PIN');
    const out = html(
      h(WorkforceDocument, {
        ...base,
        children: 'x',
        signature: { name: 'Faith Njeri', roleLine: 'Faith Njeri · Branch Manager', signedLine: 'Signed with PIN · 9 Oct 2026, 16:05' },
        qr: { value: 'LVE-0031', caption: 'Scan to open LVE-0031' },
      })
    );
    expect(out).toContain('font-wds-signature');
    expect(out).toContain('Signed with PIN');
    expect(out).toContain('width="76"');
    expect(out).toContain('Scan to open LVE-0031');
  });
  it('heading and paragraph use the body sizes', () => {
    expect(html(h(DocHeading, { children: 'H' }))).toContain('text-[16px]');
    expect(html(h(DocParagraph, { children: 'P' }))).toContain('text-[15px]');
  });
  it('the canvas has a print button only when the viewer may print', () => {
    expect(html(h(DocumentCanvas, { children: 'x' }))).not.toContain('<button');
    expect(html(h(DocumentCanvas, { onPrint: noop, children: 'x' }))).toContain('Print');
  });
});
