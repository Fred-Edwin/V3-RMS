'use client';

import * as React from 'react';
import { QRCodeSVG } from 'qrcode.react';

import { cn } from '@/lib/cn';

import { DOC_COLOURS, DOC_PAGE, type DocOrientation } from '../../lib/style/document-palette';

/**
 * The printed Workforce document: leave slip, rota print, timesheet, payslip, pay run summary, voucher
 * (Paper 1E9N-0 and its sisters). One shell, the body is the screen's:
 *
 *   navy 10 px bar, then the header (round logo, "Wendo Coffee Bistro" and the branch at the left;
 *   the document type, its number and the date at the right), the body in Times New Roman, an optional
 *   signature block ("Signed with PIN") with a QR, and the footer.
 *
 * A4 portrait is 794 × 1123; landscape (the rota print) is 1123 × 794. Colours come from
 * `lib/document-palette.ts`, the printed page's own palette. `print-exact` keeps the bar and the logo
 * when the browser prints. The page is a plain `<article>`: no role, no data, no print button; a screen
 * wraps it in `DocumentCanvas` if it wants the grey desk and the button.
 */

const SERIF = "'Times New Roman', Times, serif";

/**
 * The cursive signature shows only the first and second name, so a long name never takes over the page. Anything in brackets is
 * dropped ("Faith Njeri (BM Nyeri Town)" signs as "Faith Njeri"); the full name stays in the plain line under it.
 */
export function signatureName(full: string): string {
  return full.replace(/\([^)]*\)/g, ' ').trim().split(/\s+/).slice(0, 2).join(' ');
}

export interface DocumentSignature {
  /** "Faith Njeri": shown in the signature font. */
  name: string;
  /** "Faith Njeri · Branch Manager". */
  roleLine: string;
  /** "Signed with PIN · 9 Oct 2026, 16:05". */
  signedLine: string;
}

export function WorkforceDocument({
  type,
  number,
  date,
  branchLine,
  orientation = 'portrait',
  children,
  signature,
  qr,
  footerLeft,
  footerRight,
  className,
}: {
  /** "LEAVE SLIP", in capitals. */
  type: string;
  /** "LVE-0031". */
  number: string;
  /** "9 October 2026". */
  date: string;
  /** "Nyeri Town branch · Nyeri, Kenya". */
  branchLine: string;
  orientation?: DocOrientation;
  children: React.ReactNode;
  signature?: DocumentSignature;
  /** What the QR opens, and the line under it ("Scan to open LVE-0031"). */
  qr?: { value: string; caption: string };
  /** "Generated by Wendo RMS · LVE-0031 · Page 1 of 1". */
  footerLeft: string;
  /** "Approved by the Branch Manager". */
  footerRight?: string;
  className?: string;
}) {
  const page = DOC_PAGE[orientation];
  return (
    <article
      data-orientation={orientation}
      className={cn('print-exact relative mx-auto flex max-w-full flex-col bg-white text-[13px] leading-4 shadow-wds-md print:shadow-none', className)}
      style={{ width: page.width, minHeight: page.height, fontFamily: SERIF, color: DOC_COLOURS.ink }}
    >
      <div aria-hidden className="h-2.5 shrink-0" style={{ backgroundColor: DOC_COLOURS.navy }} />
      <div className="flex grow flex-col px-[52px] pt-11">
        <header className="flex items-start justify-between border-b pb-5" style={{ borderColor: DOC_COLOURS.rule }}>
          <div className="flex items-center gap-3.5">
            <div aria-hidden className="size-[52px] shrink-0 rounded-full bg-cover bg-center" style={{ backgroundImage: 'url(/images/wendo-logo.jpg)' }} />
            <div className="flex flex-col gap-0.5">
              <span className="text-[23px] font-bold leading-7" style={{ color: DOC_COLOURS.navy }}>
                Wendo Coffee Bistro
              </span>
              <span className="text-[13px] leading-4 text-wds-neutral-700">{branchLine}</span>
            </div>
          </div>
          <div className="flex flex-col items-end gap-[3px]">
            <span className="text-[11px] leading-[14px] tracking-[0.14em] text-wds-neutral-700">{type}</span>
            <span className="text-[23px] font-bold leading-7" style={{ color: DOC_COLOURS.navy }}>
              {number}
            </span>
            <span className="text-[13px] leading-4 text-wds-neutral-700">{date}</span>
          </div>
        </header>

        <div className="flex grow flex-col">{children}</div>

        {signature || qr ? (
          <div className="mt-[26px] flex items-end justify-between">
            {signature ? (
              <div className="flex w-[300px] shrink-0 flex-col gap-[5px]">
                <span className="font-wds-signature text-[38px] leading-[42px]" style={{ color: DOC_COLOURS.navy }}>
                  {signatureName(signature.name)}
                </span>
                <div className="h-px shrink-0" style={{ backgroundColor: DOC_COLOURS.ink }} />
                <span className="text-[14px] leading-[18px]">{signature.roleLine}</span>
                <span className="text-[12px] leading-4 text-wds-neutral-700">{signature.signedLine}</span>
              </div>
            ) : (
              <span />
            )}
            {qr ? (
              <div className="flex flex-col items-center gap-[5px]">
                <QRCodeSVG value={qr.value} size={76} marginSize={0} fgColor={DOC_COLOURS.ink} aria-label={qr.caption} />
                <span className="text-[11px] leading-[14px] text-wds-neutral-700">{qr.caption}</span>
              </div>
            ) : null}
          </div>
        ) : null}

        <footer className="mt-auto flex justify-between border-t pb-[18px] pt-3.5 text-[12px] leading-4 text-wds-neutral-700" style={{ borderColor: DOC_COLOURS.rule }}>
          <span>{footerLeft}</span>
          {footerRight ? <span>{footerRight}</span> : null}
        </footer>
      </div>
    </article>
  );
}

/** A navy heading inside a document body ("Annual leave approved: ..."). */
export function DocHeading({ children }: { children: React.ReactNode }) {
  return (
    <h2 className="m-0 mt-[22px] text-[16px] font-bold leading-5" style={{ color: DOC_COLOURS.navy }}>
      {children}
    </h2>
  );
}

/** A body paragraph: 15 px on 22. */
export function DocParagraph({ children, muted = false }: { children: React.ReactNode; muted?: boolean }) {
  return <p className={cn('m-0 mt-3 text-[15px] leading-[22px]', muted && 'text-wds-neutral-700')}>{children}</p>;
}

/** The grey desk the page sits on, with an optional Print button (hidden when printing). */
export function DocumentCanvas({ children, onPrint, printLabel = 'Print', width = 794 }: { children: React.ReactNode; /** Pass only if the viewer may print. */ onPrint?: () => void; printLabel?: string; /** The page's width, so the Print button sits over its right edge (1123 for landscape). */ width?: number }) {
  return (
    <div className="min-h-screen bg-wds-neutral-100 py-6 print:bg-white print:py-0">
      {onPrint ? (
        <div className="mx-auto mb-4 flex max-w-full items-center justify-end px-1 print:hidden" style={{ width }}>
          <button type="button" onClick={onPrint} className="h-8 rounded-wds-sm bg-wds-primary px-4 font-wds-sans text-[13px] font-medium text-wds-primary-fg outline-none focus-visible:shadow-wds-ring">
            {printLabel}
          </button>
        </div>
      ) : null}
      {children}
    </div>
  );
}
