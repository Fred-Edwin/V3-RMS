import { shortDayTime } from '../../_shared/lib/conduct-dates';
import type { FileTab } from '../../_shared/types/conduct-types';

/**
 * "What happened, in order" (spec S14): a time and a sentence for each event, oldest first, from the notice events (never the audit log).
 * Names carry their role. The system's own events say "The system".
 */
export function FileTimeline({ rows }: { rows: FileTab['timeline'] }) {
  return (
    <section aria-labelledby="timeline-h" className="flex flex-col gap-2">
      <h3 id="timeline-h" className="m-0 font-wds-mono text-[10px] font-normal leading-3 tracking-[0.08em] text-wds-text-secondary">
        WHAT HAPPENED, IN ORDER
      </h3>
      <ol className="m-0 flex list-none flex-col p-0">
        {rows.map((row, i) => (
          <li key={`${row.at}-${i}`} className="flex gap-4 border-b border-wds-neutral-100 py-2.5">
            <time dateTime={row.at} className="w-[120px] shrink-0 font-wds-mono text-[11px] leading-4 text-wds-text-secondary">
              {shortDayTime(row.at)}
            </time>
            <span className="font-wds-sans text-[13px] leading-[18px] text-wds-text-ink">{row.text}</span>
          </li>
        ))}
      </ol>
    </section>
  );
}

/** "Who can see conduct": generated by the server from the access table, so it cannot drift from what is enforced. */
export function FileAccessTable({ rows }: { rows: FileTab['access'] }) {
  return (
    <aside aria-labelledby="access-h" className="flex flex-col gap-2 border border-wds-border bg-wds-surface p-4">
      <h3 id="access-h" className="m-0 font-wds-mono text-[10px] font-normal leading-3 tracking-[0.08em] text-wds-text-secondary">
        WHO CAN SEE CONDUCT
      </h3>
      <dl className="m-0 flex flex-col">
        {rows.map((row) => (
          <div key={row.role} className="flex items-baseline justify-between gap-3 border-b border-wds-neutral-100 py-2 last:border-b-0">
            <dt className="font-wds-sans text-[13px] leading-4 text-wds-text-ink">{row.role}</dt>
            <dd className="m-0 text-right font-wds-sans text-[12px] leading-4 text-wds-text-secondary">{row.text}</dd>
          </div>
        ))}
      </dl>
      <p className="m-0 font-wds-sans text-[12px] leading-[17px] text-wds-text-secondary">Reading this tab is logged. A manager sees only their own site.</p>
    </aside>
  );
}
