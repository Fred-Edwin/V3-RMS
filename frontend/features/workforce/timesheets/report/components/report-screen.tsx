'use client';

import * as React from 'react';
import Link from 'next/link';
import { useSearchParams } from 'next/navigation';

import { DOC_COLOURS, DialogButton, DocumentCanvas, EmptyState, ErrorBlock, ListSkeleton, WorkforceDocument, useWorkforcePermissions } from '../../../_shared';
import { ReopenDialog } from '../../periods/components/reopen-dialog';
import { useReport } from '../../_shared/hooks/use-timesheet-data';
import { ROLE_WORDS, closedWhen, monthOf, stampOf } from '../../_shared/lib/timesheet-words';
import { statusLine } from '../lib/report-view';
import { ReportTable } from './report-table';
import { SignDialog } from './sign-dialog';

const PAGE_RULE = '@media print { @page { size: A4 landscape; margin: 0; } }';
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * The timesheet report (Paper Chapter 8, step 5): the same figures as the screen, one landscape page, printable. Everyone who may read
 * timesheets reads it. After the close the manager signs it with a PIN; HR can reopen the month from here. Hours only, no pay figure.
 * Payroll's receipt is recorded here once payroll exists (slice 6); until then the page says so.
 */
export function ReportScreen() {
  const periodId = useSearchParams().get('period') ?? '';
  const permissions = useWorkforcePermissions();
  const valid = UUID.test(periodId);
  const report = useReport(periodId, valid && permissions.ready && permissions.can('timesheet.read'));
  const [dialog, setDialog] = React.useState<'sign' | 'reopen' | null>(null);

  if (!valid) return <EmptyState kind="nothingFound" title="Pick a month first" line="Open a report from the Timesheets page." className="m-8" />;
  if (!permissions.ready && !permissions.failed) return <ListSkeleton rows={6} label="Preparing the report" className="m-8" />;
  if (permissions.failed || !permissions.can('timesheet.read')) return <EmptyState kind="nothingYet" title="You can't open this report" line="Ask HR if you need a copy." className="m-8" />;
  if (report.status === 'error' && !report.data) return <ErrorBlock title="The report did not load" line={report.error.message} reference={report.error.code} onRetry={report.reload} className="m-8" />;
  const data = report.data;
  if (!data) return <ListSkeleton rows={6} label="Preparing the report" className="m-8" />;

  const { period, signatures } = data;
  const closed = period.state === 'CLOSED';
  const signer = signatures.signedBy;
  const done = (): void => {
    setDialog(null);
    report.reload();
  };
  return (
    <DocumentCanvas onPrint={() => window.print()} printLabel="Print the report" width={1123}>
      <style>{PAGE_RULE}</style>
      <div className="mx-auto mb-3 flex max-w-full items-center justify-between gap-3 px-1 print:hidden" style={{ width: 1123 }}>
        <Link href="/app/workforce/timesheets" className="font-wds-sans text-[13px] text-wds-text-secondary underline-offset-2 hover:text-wds-text-ink hover:underline">
          ← Back to Timesheets
        </Link>
        <div className="flex items-center gap-2">
          {closed && !signer && permissions.can('timesheet.close') ? (
            <DialogButton kind="cancel" onClick={() => setDialog('sign')}>
              Sign this report
            </DialogButton>
          ) : null}
          {closed && permissions.can('timesheet.reopen') ? (
            <DialogButton kind="cancel" onClick={() => setDialog('reopen')}>
              Reopen with a reason
            </DialogButton>
          ) : null}
        </div>
      </div>
      <WorkforceDocument
        orientation="landscape"
        type="TIMESHEET"
        number={data.number}
        date={closed ? `Closed ${closedWhen(period)}` : monthOf(period)}
        branchLine={`${data.organization} · ${monthOf(period)}`}
        signature={signer ? { name: signer.name, roleLine: `${signer.name} · ${ROLE_WORDS[signer.role] ?? signer.role}`, signedLine: `Signed with PIN, ${stampOf(signer.at)}` } : undefined}
        qr={{ value: typeof window === 'undefined' ? data.number : `${window.location.origin}/app/workforce/timesheets/report?period=${period.id}`, caption: `Scan to open ${data.number}` }}
        footerLeft={`Generated by Wendo RMS · ${data.number} · Page 1 of 1`}
        footerRight={closed ? (signer ? 'Payroll’s receipt is recorded here when payroll receives it' : 'Waiting for the manager’s signature') : 'Not closed yet: figures can still change'}
      >
        <div className="mt-4">
          <span className="inline-block border-2 px-3 py-1 text-[13px] font-bold tracking-[0.16em]" style={{ borderColor: DOC_COLOURS.navy, color: DOC_COLOURS.navy }}>
            {statusLine(data)}
          </span>
        </div>
        <ReportTable report={data} />
      </WorkforceDocument>
      {dialog === 'sign' ? <SignDialog report={data} onClose={() => setDialog(null)} onDone={done} /> : null}
      {dialog === 'reopen' ? <ReopenDialog period={period} onClose={() => setDialog(null)} onDone={done} /> : null}
    </DocumentCanvas>
  );
}
